#!/usr/bin/env bash
set -e

# Perform additional database adjustments or setup multiple databases
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $POSTGRES_CENSUS_USER WITH PASSWORD '$POSTGRES_CENSUS_PASSWORD';
    CREATE DATABASE $POSTGRES_CENSUS_DB OWNER $POSTGRES_CENSUS_USER;
    
    CREATE USER $POSTGRES_DAGSTER_USER WITH PASSWORD '$POSTGRES_DAGSTER_PASSWORD';
    CREATE DATABASE $POSTGRES_DAGSTER_DB OWNER $POSTGRES_DAGSTER_USER;
EOSQL